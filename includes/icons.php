/**
 * Render crisp inline SVG icon
 */
function svg_icon(string $name, string $class = '', ?int $size = null): string {
    $clean = strtolower(trim($name));
    $clean = preg_replace('/\bfa-(solid|regular|brands|light|thin|duotone|xs|sm|lg|xl|2x|3x|fw|spin|pulse|beat|fade)\b/', '', $clean);
    $clean = preg_replace('/^fa-/', '', trim($clean));
    if (str_contains($clean, ' ')) {
        foreach (explode(' ', $clean) as $part) {
            $part = ltrim(trim($part), 'fa-');
            if ($part !== '') {
                $clean = $part;
                break;
            }
        }
    }
    $clean = preg_replace('/^fa-/', '', trim($clean));

    $paths = get_svg_icon_paths();
    $inner = $paths[$clean] ?? $paths['circle-info'];

    $sizeAttr = $size !== null
        ? ' width="' . $size . '" height="' . $size . '"'
        : ' width="1em" height="1em"';

    $cls = trim('erp-svg-icon ' . $class);
    return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.9" stroke-linecap="round" stroke-linejoin="round"' . $sizeAttr . ' class="' . e($cls) . '" aria-hidden="true">' . $inner . '</svg>';
}

/**
 * Automatically replaces any legacy <i class="fa-..."></i> tags inside an HTML fragment with crisp SVGs
 */
function replace_fa_tags_with_svg(string $html): string {
    if ($html === '' || stripos($html, 'fa-') === false) {
        return $html;
    }

    return (string)preg_replace_callback(
        '/<i\b([^>]*)class=["\']([^"\']*\bfa-[^"\']*)["\']([^>]*)><\/i>/i',
        function (array $m): string {
            $classList = $m[2];
            $tokens = preg_split('/\s+/', trim($classList)) ?: [];
            $iconName = 'circle-info';
            $extraClasses = [];
            $skip = ['fa', 'fa-solid', 'fa-regular', 'fa-brands', 'fa-light', 'fa-thin', 'fa-duotone', 'fa-xs', 'fa-sm', 'fa-lg', 'fa-xl', 'fa-2x', 'fa-3x', 'fa-fw'];
            $paths = get_svg_icon_paths();

            foreach ($tokens as $tok) {
                if (in_array($tok, $skip, true)) {
                    continue;
                }
                if (str_starts_with($tok, 'fa-')) {
                    $cand = substr($tok, 3);
                    if (isset($paths[$cand])) {
                        $iconName = $cand;
                        continue;
                    }
                    if ($tok === 'fa-spin') {
                        $extraClasses[] = 'svg-spin';
                        continue;
                    }
                }
                $extraClasses[] = $tok;
            }

            return svg_icon($iconName, implode(' ', $extraClasses));
        },
        $html
    );
}
